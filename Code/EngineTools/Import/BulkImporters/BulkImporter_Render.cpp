    void SkeletalMeshBulkImporter::ImportFile( FileImportContext const& ctx )
    {
        // Import the mesh with its materials
        //-------------------------------------------------------------------------

        Import::ReaderContext readerCtx = { ctx.m_sourceDataDirectoryPath, [&ctx] ( char const* pString ) { ctx.LogWarning( pString ); }, [&ctx] ( char const* pString ) { ctx.LogError( pString ); } };
        TUniquePtr<Import::Mesh> importedMesh = Import::Importer::ReadSkeletalMesh( readerCtx, ctx.m_fileToImport.m_filePath );

        if ( importedMesh == nullptr )
        {
            ctx.LogError( "Failed to read source mesh: %s", ctx.m_fileToImport.m_filePath.c_str() );
            return;
        }

        FileSystem::Path const textureSearchOverrideFilePath = m_textureSearchOverridePath.IsValid() ? m_textureSearchOverridePath.GetFileSystemPath( ctx.m_sourceDataDirectoryPath ) : FileSystem::Path();
        importedMesh->FinalizeMaterials( ctx.m_sourceDataDirectoryPath, textureSearchOverrideFilePath );

        // Create descriptor
        //-------------------------------------------------------------------------

        Render::SkeletalMeshResourceDescriptor descriptor;
        descriptor.m_meshPath = ctx.m_fileToImport.m_path;
        descriptor.m_meshGroup = m_meshGroup;

        // Assign materials to descriptor
        //-------------------------------------------------------------------------

        SetupMaterialsForDescriptor( ctx, importedMesh, descriptor );

        // Save descriptor
        //-------------------------------------------------------------------------

        Log log;
        if ( !Resource::ResourceDescriptor::TryWriteToFile( ctx.m_typeRegistry, log, ctx.m_targetFilePath, &descriptor ) )
        {
            ctx.AppendLog( log );
        }
    }

