    ResourceID RenderMeshBulkImporter::FindOrCreateTexture( FileImportContext const& ctx, Material::Property const& materialProperty, char const* pTextureGroupName, ResourceID const& defaultTextureID ) const
    {
        EE_ASSERT( pTextureGroupName != nullptr );

        if ( !materialProperty.HasTexture() )
        {
            return defaultTextureID;
        }

        DataPath const textureSourceFileDataPath( materialProperty.m_resolvedTexturePath, ctx.m_sourceDataDirectoryPath );

        // Check if a texture with this name already exists
        //-------------------------------------------------------------------------

        DataPath textureDataPath = textureSourceFileDataPath;
        textureDataPath.ReplaceExtension( Render::TextureResource::GetStaticResourceTypeID().ToFileSystemExtension() );
       
        FileSystem::Path const textureFilePath = textureDataPath.GetFileSystemPath( ctx.m_sourceDataDirectoryPath );
        if ( textureFilePath.Exists() )
        {
            return textureDataPath;
        }

        // Create descriptor
        //-------------------------------------------------------------------------

        Render::TextureResourceDescriptor textureDescriptor;
        textureDescriptor.m_sourcePaths.emplace_back( textureSourceFileDataPath );
        textureDescriptor.m_textureGroup = DataPath( pTextureGroupName );

        // Save descriptor
        //-------------------------------------------------------------------------

        Log log;
        if ( !Resource::ResourceDescriptor::TryWriteToFile( ctx.m_typeRegistry, log, textureFilePath, &textureDescriptor ) )
        {
            ctx.LogError( "Failed to save descriptor: %s", textureFilePath.c_str() );
            return defaultTextureID;
        }

        return textureDataPath;
    }

    ResourceID RenderMeshBulkImporter::FindOrCreateTexturePBR( FileImportContext const& ctx, Material const& material, ResourceID const& defaultTextureID ) const
    {
        if ( !material.m_metalness.HasTexture() && !material.m_roughness.HasTexture() && !material.m_occlusion.HasTexture() )
        {
            return defaultTextureID;
        }

        // Check if a texture with this name already exists
        //-------------------------------------------------------------------------

        String const textureFilename = String( String::CtorSprintf(), "%s_PBR.%s", material.m_ID.c_str(), Render::TextureResource::GetStaticResourceTypeID().ToString().c_str() );
        FileSystem::Path const textureFilePath = ctx.m_targetFilePath.GetParentDirectory().AppendFilename( textureFilename );
        DataPath const textureDataPath( textureFilePath, ctx.m_sourceDataDirectoryPath );

        if ( textureFilePath.Exists() )
        {
            return textureDataPath;
        }

        // Create descriptor
        //-------------------------------------------------------------------------

        Render::TextureResourceDescriptor textureDescriptor;
        textureDescriptor.m_textureGroup = DataPath( "data://Render/TextureGroups/PBRTexture.txtg" );

        auto const AddChannel = [&textureDescriptor, &ctx] ( Material::Property const& materialProperty, char const* pDefault )
        {
            textureDescriptor.m_sourcePaths.emplace_back( materialProperty.HasTexture() ? DataPath( materialProperty.m_resolvedTexturePath, ctx.m_sourceDataDirectoryPath ) : DataPath( pDefault ) );
        };

        AddChannel( material.m_roughness, "data://Render/Textures/White_16x16.png" );
        AddChannel( material.m_metalness, "data://Render/Textures/Black_16x16.png" );
        AddChannel( material.m_occlusion, "data://Render/Textures/White_16x16.png" );
        AddChannel( material.m_displacement, "data://Render/Textures/Black_16x16.png" );

        // Save descriptor
        //-------------------------------------------------------------------------

        Log log;
        if ( !Resource::ResourceDescriptor::TryWriteToFile( ctx.m_typeRegistry, log, textureFilePath, &textureDescriptor ) )
        {
            ctx.LogError( "Failed to save descriptor: %s", textureFilePath.c_str() );
            return defaultTextureID;
        }

        return textureDataPath;
    }

    void RenderMeshBulkImporter::CreateMaterialDescriptor( FileImportContext const& ctx, Material const& material, FileSystem::Path const& materialFilePath ) const
    {
        EE_ASSERT( materialFilePath.IsValid() );

        // Create Descriptor
        //-------------------------------------------------------------------------

        Render::MaterialResourceDescriptor descriptor;
        descriptor.m_shader = StringID( "PrincipledPBR" );

        // Set up parameters
        //-------------------------------------------------------------------------

        descriptor.m_shaderParameters.SetInstance( EE::New<Render::Shaders::PrincipledPBRParameters>() );
        Render::Shaders::PrincipledPBRParameters* pParameters = descriptor.m_shaderParameters.GetAs<Render::Shaders::PrincipledPBRParameters>();

        pParameters->m_shaderFlags = ( material.m_isTwoSided ? (int32_t) Render::MaterialShaderFlags::TwoSided : 0 );
        pParameters->m_opacity = material.m_opacity;
        pParameters->m_emissiveStrength = material.m_emissiveStrength;

        if ( material.m_albedo.m_isValueSet )
        {
            pParameters->m_albedoColor = material.m_albedo.m_value;
        }

        if ( material.m_emissive.m_isValueSet )
        {
            pParameters->m_emissiveColor = material.m_emissive.m_value;
        }

        if ( material.m_metalness.m_isValueSet )
        {
            pParameters->m_metalness = material.m_metalness.m_value.ToFloat4().m_x;
        }

        if ( material.m_roughness.m_isValueSet )
        {
            pParameters->m_roughness = material.m_roughness.m_value.ToFloat4().m_x;
        }

        if ( material.m_occlusion.m_isValueSet )
        {
            pParameters->m_occlusion = material.m_occlusion.m_value.ToFloat4().m_x;
        }

        // Setup Textures
        //-------------------------------------------------------------------------

        pParameters->m_albedoTexture = FindOrCreateTexture( ctx, material.m_albedo, "data://Render/TextureGroups/AlbedoTexture.txtg", pParameters->m_albedoTexture.GetResourceID() );
        pParameters->m_normalTexture = FindOrCreateTexture( ctx, material.m_normal, "data://Render/TextureGroups/NormalTexture.txtg", pParameters->m_normalTexture.GetResourceID() );
        pParameters->m_emissiveTexture = FindOrCreateTexture( ctx, material.m_emissive, "data://Render/TextureGroups/Uncompressed4Channels.txtg", pParameters->m_emissiveTexture.GetResourceID() );
        pParameters->m_pbrTexture = FindOrCreateTexturePBR( ctx, material, pParameters->m_pbrTexture.GetResourceID() );

        EE_ASSERT( pParameters->m_albedoTexture.IsSetAndIsValidResourceTypeID() );
        EE_ASSERT( pParameters->m_normalTexture.IsSetAndIsValidResourceTypeID() );
        EE_ASSERT( pParameters->m_emissiveTexture.IsSetAndIsValidResourceTypeID() );
        EE_ASSERT( pParameters->m_pbrTexture.IsSetAndIsValidResourceTypeID() );

        // Save descriptor
        //-------------------------------------------------------------------------

        Log log;
        if ( !Resource::ResourceDescriptor::TryWriteToFile( ctx.m_typeRegistry, log, materialFilePath, &descriptor ) )
        {
            ctx.AppendLog( log );
        }
    }

    void RenderMeshBulkImporter::SetupMaterialsForDescriptor( FileImportContext const& ctx, TUniquePtr<Import::Mesh> const& importedMesh, Render::MeshResourceDescriptor& descriptor ) const
    {
        // Get mesh group
        //-------------------------------------------------------------------------

        Log log;
        Render::MeshGroup meshGroup;
        auto const readResult = Render::MeshGroup::TryReadFromFile( ctx.m_typeRegistry, log, descriptor.m_meshGroup.GetFileSystemPath( ctx.m_sourceDataDirectoryPath ), meshGroup );
        if ( !readResult.m_succeeded )
        {
            ctx.AppendLog( log );
            ctx.LogError( "Failed to read mesh group: %s", descriptor.m_meshGroup.c_str() );
            return;
        }

        if ( meshGroup.m_lodSettings.empty() )
        {
            Render::MeshLODSettings& defaultLOD = meshGroup.m_lodSettings.emplace_back();
            defaultLOD.m_lodDistance = 0.0f;
        }

        // Create Materials
        //-------------------------------------------------------------------------

        THashMap<StringID, DataPath> materialPaths;

        for ( auto const& material : importedMesh->GetMaterials() )
        {
            EE_ASSERT( material.m_ID.IsValid() );

            // Generate material filename
            DataPath materialPath = ctx.m_fileToImport.m_path.GetParentDirectory();
            materialPath.AppendFilename( InlineString( InlineString::CtorSprintf(), "%s.%s", material.m_ID.c_str(), Render::Material::GetStaticResourceTypeID().ToString().c_str() ) );

            // Check if material exists, if not create it
            FileSystem::Path const materialFilePath = materialPath.GetFileSystemPath( ctx.m_sourceDataDirectoryPath );
            if ( !materialFilePath.Exists() )
            {
                CreateMaterialDescriptor( ctx, material, materialFilePath );
            }

            materialPaths.emplace( material.m_ID, materialPath );
        }

        // Assign Materials
        //-------------------------------------------------------------------------

        for ( int32_t lodIndex = 0; lodIndex < int32_t( meshGroup.m_lodSettings.size() ); lodIndex++ )
        {
            uint8_t const lodMask = uint8_t( 1 ) << uint8_t( lodIndex );

            for ( Mesh::Submesh const& submesh : importedMesh->GetSubmeshes() )
            {
                Render::MeshMaterialMapping& mapping = descriptor.m_materialMappings.emplace_back();
                mapping.m_mappingID = Render::MeshMaterialMapping::CreateMappingID( submesh.m_ID, submesh.m_materialID, lodMask );

                auto foundMaterialPathIter = materialPaths.find( submesh.m_materialID );
                if ( foundMaterialPathIter != materialPaths.end() )
                {
                    mapping.m_material = ResourceID( foundMaterialPathIter->second );
                }
            }
        }
    }

